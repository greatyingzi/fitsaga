#!/usr/bin/env python3
import subprocess, json, pathlib, re, time
ROOT=pathlib.Path("/Users/liheng/work/self/fitsaga"); OUT=ROOT/"public/topics"
KEY=re.search(r"zai:[\s\S]*?api_key:\s*(\S+)",open("/Users/liheng/.hermes/config.yaml").read()).group(1)
PAIRS={
 "failure-cases-postmortem":("autopsy report style, five failed AI fashion images with red X marks, annotated causes, forensic editorial design", "only polished success images"),
 "where-rules-break":("infographic with rules and boundary conditions, checkmarks and warning signs, two column comparison, clean design", "rules without context, absolute statements"),
 "before-after-deconstruction":("side by side before after comparison, prompt text with edits highlighted, decision annotations, editorial layout", "final result only, no process"),
 "edge-cases-of-hanfu":("hanfu garments with exception labels, museum style annotated diagram, clean reference sheet", "single rigid rule diagram"),
 "what-we-stopped-believing":("ten crossed out belief cards, scientific myth busting design, elegant dark editorial", "ten unchallenged beliefs poster"),
}
def gen_img(p,out):
    b=json.dumps({"model":"cogview-3-flash","prompt":p,"size":"1024x1024"})
    r=subprocess.run(["curl","-s","-X","POST","https://open.bigmodel.cn/api/paas/v4/images/generations","-H",f"Authorization: Bearer {KEY}","-H","Content-Type: application/json","-d",b,"--max-time","70"],capture_output=True,text=True,timeout=80)
    try:
        u=json.loads(r.stdout)["data"][0]["url"]
        subprocess.run(["curl","-sL",u,"-o",out,"--max-time","60"],capture_output=True,timeout=70)
        return pathlib.Path(out).exists() and pathlib.Path(out).stat().st_size>10000
    except: return False
ok=0
for slug,(g,b) in PAIRS.items():
    d=OUT/slug; d.mkdir(parents=True,exist_ok=True)
    a=gen_img(g,str(d/"style-good.jpg")); time.sleep(2)
    c=gen_img(b,str(d/"style-bad.jpg")); time.sleep(2)
    ok+=(a and c); print(slug,a,c)
print("TOTAL:",ok)
